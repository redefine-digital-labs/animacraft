export const PRODUCT_MESSAGES = Object.freeze({
  en: Object.freeze(en),
  zh: Object.freeze(zh),
  ja: Object.freeze(ja),
  ko: Object.freeze(ko),
  vi: Object.freeze(vi),
});

export function normalizeProductLocale(value) {
  const normalized = String(value || '').toLowerCase().split('-')[0];
  return PRODUCT_LOCALES.includes(normalized) ? normalized : 'en';
}

export function productMessage(locale, key) {
  const normalized = normalizeProductLocale(locale);
  return PRODUCT_MESSAGES[normalized][key] ?? PRODUCT_MESSAGES.en[key] ?? key;
}

export function assertProductMessagesComplete() {
  const reference = Object.keys(PRODUCT_MESSAGES.en).sort();
  for (const locale of PRODUCT_LOCALES) {
    const keys = Object.keys(PRODUCT_MESSAGES[locale]).sort();
    if (keys.length !== reference.length || keys.some((key, index) => key !== reference[index])) {
      throw new Error(`Product locale ${locale} does not match the English vocabulary.`);
    }
  }
  return true;
}

assertProductMessagesComplete();
